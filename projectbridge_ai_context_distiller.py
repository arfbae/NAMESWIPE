def parse_files_csv(csv_filepath: Path) -> list:
    """Reads files.csv generated by FileBreaker and normalizes data."""
    if not csv_filepath.exists():
        print(f"[Error] Could not find '{csv_filepath}'. Please place 'files.csv' in this folder.")
        sys.exit(1)

    records = []
    with open(csv_filepath, mode='r', encoding='utf-8', errors='ignore') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Handle variations in header naming between FileBreaker versions
            name = row.get('Name') or row.get('name') or row.get('file') or 'Unknown'
            ext = row.get('Extension') or row.get('extension') or '[no ext]'
            path_str = row.get('FullPath') or row.get('path') or row.get('folder') or ''
            
            # Size handling (MB or Bytes)
            size_mb = 0.0
            if 'Size_MB' in row or 'size_mb' in row:
                size_mb = float(row.get('Size_MB') or row.get('size_mb') or 0.0)
            elif 'size' in row or 'sizebytes' in row:
                bytes_val = float(row.get('size') or row.get('sizebytes') or 0.0)
                size_mb = bytes_val / (1024 * 1024)

            records.append({
                "name": name,
                "extension": ext.lower(),
                "path": path_str,
                "size_mb": size_mb
            })
    return records

def summarize_inventory(records: list) -> dict:
    """Distills tens of thousands of rows into clean high-level intelligence."""
    total_files = len(records)
    total_size_mb = sum(r['size_mb'] for r in records)
    total_size_gb = total_size_mb / 1024.0

    # Aggregate by Extension
    ext_map = defaultdict(lambda: {"count": 0, "size_mb": 0.0})
    for r in records:
        ext = r['extension']
        ext_map[ext]["count"] += 1
        ext_map[ext]["size_mb"] += r['size_mb']

    sorted_exts = sorted(ext_map.items(), key=lambda x: x[1]["size_mb"], reverse=True)

    # Aggregate by Folder Path
    folder_map = defaultdict(lambda: {"count": 0, "size_mb": 0.0})
    for r in records:
        # Extract directory name
        p = r['path']
        sep = '\\' if '\\' in p else '/'
        folder = p.rsplit(sep, 1)[0] if sep in p else 'Root'
        folder_map[folder]["count"] += 1
        folder_map[folder]["size_mb"] += r['size_mb']

    sorted_folders = sorted(folder_map.items(), key=lambda x: x[1]["size_mb"], reverse=True)

    # Find Top 5 Outlier Files (> 100MB)
    outliers = sorted(records, key=lambda x: x['size_mb'], reverse=True)[:5]

    return {
        "total_files": total_files,
        "total_size_gb": round(total_size_gb, 2),
        "top_extensions": sorted_exts[:5],
        "top_folders": sorted_folders[:5],
        "largest_files": outliers
    }

def generate_ai_snapshot(summary: dict, project_name="AssetBreaker Local Inventory") -> str:
    """Generates a structured, concise Markdown prompt meant for LLM consumption."""
    
    ext_rows = "\n".join([f"  - `{ext}`: {data['count']:,} files ({data['size_mb']/1024:.2f} GB)" for ext, data in summary['top_extensions']])
    folder_rows = "\n".join([f"  - `{folder}`: {data['count']:,} files ({data['size_mb']/1024:.2f} GB)" for folder, data in summary['top_folders']])
    outlier_rows = "\n".join([f"  - `{f['name']}` ({f['size_mb']:.1f} MB) in `{f['path']}`" for f in summary['largest_files']])

    markdown = f"""# PROJECT CONTEXT SNAPSHOT: {project_name}
> Generated by ProjectBridge | Optimized for LLM Context Windows

## 1. Executive Summary
- **Total Files Scanned:** {summary['total_files']:,}
- **Total Storage Consumed:** {summary['total_size_gb']:.2f} GB
- **System Status:** Scan complete, data distilled for analysis.

## 2. Top Storage Consuming Extensions
{ext_rows}

## 3. Top Storage Consuming Folders
{folder_rows}

## 4. Largest File Outliers
{outlier_rows}

## 5. Locked System Guardrails
- **Read-Only Mode:** Active. No filesystem write or delete permissions granted.
- **Goal:** Provide organization, cleanup recommendations, or visual mapping suggestions without moving files automatically.

---
*Instructions for AI:* Review this project snapshot and propose high-value organization strategies, redundant extension targets, or structure improvements.
"""
    return markdown

